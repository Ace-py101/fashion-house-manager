# =========================================================
# PUBLIC HELPERS
# =========================================================

def get_measurement_template(
    garment_name
):
    """
    Return the measurement template
    for a garment.
    """

    if not garment_name:

        return []

    garment_name = garment_name.strip()

    return GARMENT_MEASUREMENT_TEMPLATES.get(

        garment_name,

        []

    )


def garment_has_measurements(
    garment_name
):
    """
    Return True if the garment
    has a configured measurement
    template.
    """

    return len(

        get_measurement_template(
            garment_name
        )

    ) > 0


